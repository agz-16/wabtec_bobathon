#!/usr/bin/env python3
"""Build the offline copy of the lab guide from docs/.

Usage:  python3 build-offline.py

Creates (or fully replaces) offline/ and offline.zip next to this script. offline/index.html
opens by double-click: the exercise HTML is embedded in the page, because
browsers block fetch() on file:// pages. Fonts fall back to system fonts.

Re-run this script after any change under docs/, then commit offline/.
Standard library only.
"""
import json
import re
import shutil
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent
DOCS = ROOT / "docs"
OUT = ROOT / "offline"
ZIP = ROOT / "offline.zip"

# Same order as DEFAULT_TRACK_SLUGS in docs/js/app.js.
SLUGS = ["setup", "track-1", "track-2", "track-3", "track-4", "track-5", "track-6", "track-7"]

IMG_RE = re.compile(r"""img/([A-Za-z0-9_.\- ]+\.(?:png|jpe?g|gif|svg|webp))""", re.I)
FONT_LINE_RE = re.compile(
    r'^[ \t]*<link[^>]*(?:fonts\.googleapis\.com|fonts\.gstatic\.com)[^>]*>[ \t]*\n', re.M
)


def fail(msg):
    print("ERROR: " + msg, file=sys.stderr)
    sys.exit(1)


def js_string_map(tracks):
    """JSON map that is safe to place inside a <script> element."""
    text = json.dumps(tracks, ensure_ascii=False)
    return text.replace("</", "<\\/").replace("<!--", "<\\!--")


def write_zip():
    """Zip offline/ so that unzipping gives one folder named offline/."""
    if ZIP.exists():
        ZIP.unlink()
    count = 0
    with zipfile.ZipFile(ZIP, "w", zipfile.ZIP_DEFLATED) as zf:
        for path in sorted(OUT.rglob("*")):
            if path.is_dir() or path.name.startswith("."):
                continue
            zf.write(path, Path("offline") / path.relative_to(OUT))
            count += 1
    return count


def main():
    index = DOCS / "index.html"
    if not index.is_file():
        fail("missing " + str(index))

    tracks = {}
    for slug in SLUGS:
        path = DOCS / "tracks" / (slug + ".html")
        if not path.is_file():
            fail("missing track file " + str(path))
        tracks[slug] = path.read_text(encoding="utf-8")

    html = index.read_text(encoding="utf-8")

    # 1. Drop the Google Fonts tags (not available offline).
    html, removed = FONT_LINE_RE.subn("", html)
    if removed == 0:
        fail("expected Google Fonts <link> tags in docs/index.html; none found")

    # 2. Embed the exercises before app.js so loadTrackSlug() can use them.
    marker = re.search(r'<script src="js/app\.js[^"]*"></script>', html)
    if not marker:
        fail("could not find the app.js <script> tag in docs/index.html")
    inline = "<script>window.FLIGHT400_INLINE_TRACKS = " + js_string_map(tracks) + ";</script>\n"
    html = html[: marker.start()] + inline + html[marker.start():]

    # 3. Work out which images the page needs.
    sources = [html] + list(tracks.values())
    sources.append((DOCS / "css" / "styles.css").read_text(encoding="utf-8"))
    sources.append((DOCS / "js" / "app.js").read_text(encoding="utf-8"))
    images = sorted({m.group(1) for src in sources for m in IMG_RE.finditer(src)})
    missing = [name for name in images if not (DOCS / "img" / name).is_file()]
    if missing:
        fail("images referenced but not found in docs/img: " + ", ".join(missing))

    # 4. Write offline/ from scratch so removed files do not linger.
    if OUT.exists():
        shutil.rmtree(OUT)
    (OUT / "css").mkdir(parents=True)
    (OUT / "js").mkdir()
    (OUT / "img").mkdir()

    (OUT / "index.html").write_text(html, encoding="utf-8")
    shutil.copy2(DOCS / "css" / "styles.css", OUT / "css" / "styles.css")
    shutil.copy2(DOCS / "js" / "app.js", OUT / "js" / "app.js")
    for name in images:
        shutil.copy2(DOCS / "img" / name, OUT / "img" / name)

    (OUT / "README.txt").write_text(
        "FLIGHT400 Bobathon - offline lab guide\n"
        "======================================\n\n"
        "Open index.html in your browser (double-click it). No web server and no\n"
        "internet connection are needed to read the guide.\n\n"
        "Still needs internet:\n"
        "  - The Box folder link (download your private key BEFORE going offline).\n"
        "  - Links to external sites, for example IBM i Access Client Solutions.\n\n"
        "Fonts fall back to your system fonts, so the layout looks slightly\n"
        "different from the online version.\n\n"
        "This folder is generated by build-offline.py from the docs/ folder.\n"
        "Do not edit it by hand.\n",
        encoding="utf-8",
    )

    zipped = write_zip()

    print("Wrote %s" % OUT)
    print("  tracks embedded : %d" % len(tracks))
    print("  images copied   : %d" % len(images))
    print("  fonts links removed: %d" % removed)
    print("Wrote %s (%d files, %.1f MB)" % (ZIP, zipped, ZIP.stat().st_size / 1e6))


if __name__ == "__main__":
    main()
